package io.github.jcd2052.elements;

import com.microsoft.playwright.Locator;
import com.microsoft.playwright.PlaywrightException;
import com.microsoft.playwright.options.BoundingBox;
import com.microsoft.playwright.options.MouseButton;
import io.github.jcd2052.browser.services.interfaces.ILocalizationService;
import io.github.jcd2052.exceptions.BasePlaywrightException;
import io.github.jcd2052.logger.i18n.LogAction;
import lombok.Getter;
import org.apache.commons.lang3.StringUtils;
import io.github.jcd2052.browser.browser.MouseActions;
import io.github.jcd2052.browser.browser.interfaces.IMouseActions;
import io.github.jcd2052.browser.services.interfaces.IElementFactory;
import io.github.jcd2052.browser.services.interfaces.IElementSupplier;
import io.github.jcd2052.elements.selector.Selector;
import io.github.jcd2052.elements.interfaces.IElement;
import io.github.jcd2052.elements.interfaces.IElementCollection;
import io.github.jcd2052.elements.interfaces.IJsActions;
import io.github.jcd2052.exceptions.PlaywrightExceptionParser;
import io.github.jcd2052.logger.LoggerProvider;

import java.util.Arrays;
import java.util.List;
import java.util.function.Supplier;
import java.util.stream.Collectors;

/**
 * The core abstract base class for all web elements in the framework.
 * <p>This class implements the {@link IElement} interface and provides standard wrappers
 * around Playwright's native {@link Locator} interactions. It handles common element behaviors
 * including clicking, typing, state evaluation, and dynamic child element creation.</p>
 * <p>Additionally, it integrates built-in logging, optional visual highlighting, and
 * JavaScript-based action fallbacks via {@link IJsActions}.</p>
 */
public abstract class AbstractElement implements IElement {
    private final String name;
    /**
     * The Just-In-Time locator strategy assigned to this element.
     * <p>
     * Note: The getter is automatically generated by Lombok's {@code @Getter} annotation.
     * </p>
     */
    @Getter
    private final Selector selector;
    protected final IElementFactory elementFactory;
    /**
     * Provides access to JavaScript-based element interactions.
     * <p>
     * Note: The getter is automatically generated by Lombok's {@code @Getter} annotation.
     * </p>
     */
    @Getter
    protected final IJsActions jsActions;
    protected final ILocalizationService i18n;

    /**
     * Constructs a new {@code AbstractElement}.
     *
     * @param selector       The Playwright Selector locator strategy used to find the element.
     * @param name           A human-readable name for the element, used in logging.
     * @param elementFactory The factory responsible for creating and locating elements.
     */
    protected AbstractElement(
            Selector selector,
            String name,
            IElementFactory elementFactory) {
        this.elementFactory = elementFactory;
        this.name = name;
        this.selector = selector;
        this.i18n = elementFactory.getLocalizationService();
        this.jsActions = new JsActions(this);
    }

    @Override
    public void click() {
        executeAction(() -> getLocator().click(), LogAction.ELEMENT_CLICKED);
    }

    @Override
    public void doubleClick() {
        executeAction(() -> getLocator().dblclick(), LogAction.ELEMENT_DOUBLE_CLICKED);
    }

    @Override
    public void forceClick() {
        executeAction(
                () -> getLocator().click(new Locator.ClickOptions().setForce(true)),
                LogAction.ELEMENT_FORCE_CLICKED);
    }

    @Override
    public void rightClick() {
        executeAction(
                () -> getLocator().click(new Locator.ClickOptions().setButton(MouseButton.RIGHT)),
                LogAction.ELEMENT_RIGHT_CLICKED);
    }

    @Override
    public void middleClick() {
        executeAction(
                () -> getLocator().click(new Locator.ClickOptions().setButton(MouseButton.MIDDLE)),
                LogAction.ELEMENT_MIDDLE_CLICKED);
    }

    @Override
    public void click(double x, double y) {
        executeAction(
                () -> getLocator().click(new Locator.ClickOptions().setPosition(x, y)),
                LogAction.ELEMENT_CLICKED_AT, x, y);
    }

    /**
     * Simulates pressing a specific keyboard key on the element.
     *
     * @param key The key to press (e.g., "Enter", "ArrowDown").
     */
    @Override
    public void press(String key) {
        executeAction(() -> getLocator().press(key), LogAction.KEY_PRESSED, key);
    }

    @Override
    public void dragAndDropTo(IElement targetElement, int steps) {
        executeAction(
                () -> {
                    BoundingBox sourceBox = getLocator().boundingBox();
                    BoundingBox targetBox = targetElement.getLocator().boundingBox();

                    if (sourceBox == null || targetBox == null) {
                        throw new IllegalStateException("Cannot perform dragAndDropTo: " +
                                "Source or target element is not visible.");
                    }

                    double startX = sourceBox.x + (sourceBox.width / 2);
                    double startY = sourceBox.y + (sourceBox.height / 2);
                    double endX = targetBox.x + (targetBox.width / 2);
                    double endY = targetBox.y + (targetBox.height / 2);

                    getMouseActions().move(startX, startY);
                    getMouseActions().down();
                    getMouseActions().move(endX, endY, steps);
                    getMouseActions().up();
                },
                LogAction.ELEMENT_DRAGGED_TO, targetElement.getName());
    }

    @Override
    public IMouseActions getMouseActions() {
        return new MouseActions(getLocator().page().mouse());
    }

    /**
     * Retrieves the inner text of all matching elements found by the locator strategy.
     *
     * @return A collection of inner text strings.
     */
    @Override
    public List<String> getAllTexts() {
        highlightElementIfNeeded();
        String innerText = executeActionReturning(() -> getLocator().innerText(), LogAction.TEXTS_READ);
        return Arrays.stream(innerText.split(StringUtils.LF)).collect(Collectors.toList());
    }

    /**
     * Retrieves the visible text content of the element.
     *
     * @return The text content of the element.
     */
    @Override
    public String getText() {
        highlightElementIfNeeded();
        return executeActionReturning(() -> getLocator().textContent(), LogAction.TEXT_READ);
    }

    /**
     * Retrieves the value of a specified HTML attribute from the element.
     *
     * @param name The name of the attribute (e.g., "href", "class").
     * @return The value of the attribute, or null if it does not exist.
     */
    @Override
    public String getAttribute(String name) {
        return executeActionReturning(
                () -> getLocator().getAttribute(name, new Locator.GetAttributeOptions()),
                LogAction.ATTRIBUTE_READ, name);
    }

    /**
     * Checks if the element is currently visible in the DOM.
     *
     * @return {@code true} if visible; {@code false} otherwise.
     */
    @Override
    public boolean isVisible() {
        return executeActionReturning(() -> getLocator().isVisible(), LogAction.ELEMENT_VISIBILITY_CHECKED);
    }

    /**
     * Checks if the element is currently enabled (i.e., not explicitly disabled).
     *
     * @return {@code true} if enabled; {@code false} otherwise.
     */
    @Override
    public boolean isEnabled() {
        highlightElementIfNeeded();
        return executeActionReturning(() -> getLocator().isEnabled(), LogAction.ELEMENT_ENABLED_CHECKED);
    }

    /**
     * Dynamically creates a child element scoped to this parent element using its Selector strategy.
     *
     * @param clazz    The specific class type of the child element to create.
     * @param selector The relative child Selector locator strategy.
     * @param name     The human-readable name of the child element.
     * @param <T>      The type of the child element, extending {@link IElement}.
     * @return A new instance of the specified child element type.
     */
    @Override
    public <T extends IElement> T createChildElement(Class<T> clazz, Selector selector, String name) {
        return elementFactory.createChildElement(clazz, this, selector, name);
    }

    /**
     * Dynamically creates a child element using a provided supplier, scoped to this parent element.
     *
     * @param elementSupplier The functional interface supplying the element instance.
     * @param selector        The relative child Selector locator strategy.
     * @param name            The human-readable name of the child element.
     * @param <T>             The type of the child element, extending {@link IElement}.
     * @return A new instance of the specified child element type.
     */
    @Override
    public <T extends IElement> T createChildElement(
            IElementSupplier<T> elementSupplier,
            Selector selector,
            String name) {
        return elementFactory.createChildElement(elementSupplier, this, selector, name);
    }

    /**
     * Dynamically creates a collection of child elements scoped to this parent element using its Selector strategy.
     *
     * @param clazz         The specific class type of the child elements.
     * @param selector      The relative child Selector locator strategy matching multiple items.
     * @param name          The base human-readable name for the elements.
     * @param expectedCount The expected number of elements (used for validation/waiting).
     * @param <T>           The type of the child elements, extending {@link IElement}.
     * @return An {@link IElementCollection} containing the resolved child elements.
     */
    @Override
    public <T extends IElement> IElementCollection<T> createChildElements(
            Class<T> clazz,
            Selector selector,
            String name,
            ExpectedCount expectedCount) {
        return elementFactory.createChildElementsCollection(clazz, this, selector, name, expectedCount);
    }

    /**
     * Gets the trimmed human-readable name of the element.
     *
     * @return The element's name.
     */
    @Override
    public String getName() {
        return name.trim();
    }

    /**
     * Resolves and retrieves the Playwright {@link Locator} instance for this element.
     * <p>This defers the actual DOM lookup to the {@link IElementFactory}'s finder service via
     * the assigned Selector strategy, ensuring JIT evaluation upon interaction.</p>
     *
     * @return The Playwright {@code Locator} instance.
     */
    @Override
    public Locator getLocator() {
        return elementFactory.getElementFinderService().findElement(selector);
    }

    /**
     * Triggers a visual highlight of the element on the page, provided highlighting
     * is enabled in the framework configuration via the {@code elementFactory}.
     */
    protected void highlightElementIfNeeded() {
        if (elementFactory.isHighlightEnabled()) {
            executeAction(
                    () -> getLocator().highlight(new Locator.HighlightOptions().setStyle("outline: 3px solid red")),
                    LogAction.ELEMENT_HIGHLIGHTED);
        }
    }

    /**
     * Executes a runnable action, providing centralized localized logging and exception handling.
     *
     * @param action    The Playwright action to execute.
     * @param logAction The localized action enum.
     * @param args      Any additional arguments for the log message.
     */
    protected void executeAction(Runnable action, LogAction logAction, Object... args) {
        executeActionReturning(() -> {
            action.run();
            return null;
        }, logAction, args);
    }

    /**
     * Executes a returning action, providing centralized localized logging and exception handling.
     *
     * @param <R>       The type of the result returned by the action.
     * @param action    The Playwright action returning a result to execute.
     * @param logAction The localized action enum.
     * @param args      Any additional arguments for the log message.
     * @return The result of the Playwright action.
     */
    protected <R> R executeActionReturning(Supplier<R> action, LogAction logAction, Object... args) {
        try {
            R result = action.get();
            if (logAction != null) {
                logSuccess(logAction, args);
            }
            return result;
        } catch (PlaywrightException e) {
            throw handleException(e, logAction);
        }
    }

    /**
     * Formats the arguments and logs a successful action using the localization service.
     */
    private void logSuccess(LogAction logAction, Object... args) {
        Object[] formatArgs = new Object[args.length + 1];
        formatArgs[0] = this.name;
        System.arraycopy(args, 0, formatArgs, 1, args.length);

        LoggerProvider.getLogger().info(i18n.getMessage(logAction, formatArgs));
    }

    /**
     * Parses a PlaywrightException, logs the localized error, and returns a custom framework exception.
     */
    private BasePlaywrightException handleException(PlaywrightException e, LogAction logAction) {
        BasePlaywrightException parsedException = PlaywrightExceptionParser.parse(
                e,
                this.name,
                this.selector,
                logAction.getKey()
        );

        String errorMessage = i18n.getMessage(LogAction.ACTION_FAILED, this.name, parsedException.getMessage());
        LoggerProvider.getLogger().error(errorMessage);

        return parsedException;
    }
}