package io.github.jcd2052.browser.browser;

import com.microsoft.playwright.Browser;
import com.microsoft.playwright.BrowserContext;
import com.microsoft.playwright.Page;
import com.microsoft.playwright.Playwright;
import com.microsoft.playwright.options.Geolocation;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;
import io.github.jcd2052.browser.browser.interfaces.IBrowser;
import io.github.jcd2052.browser.browser.interfaces.IBrowserWindow;
import io.github.jcd2052.browser.configuration.IBrowserProperties;

import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Concrete Playwright implementation of the {@link IBrowser} interface.
 * <p>
 * This class manages the lifecycle of a Playwright {@link Browser} instance,
 * including its contexts (windows), active state, and properties configuration.
 * <p>
 * Note: Getters for all fields in this class are automatically generated by Lombok's class-level {@code @Getter}.
 */
@Getter
public class PlaywrightBrowser implements IBrowser {
    /**
     * The raw Playwright Browser instance.
     */
    private final Browser browser;
    /**
     * The Playwright driver process that owns the browser connection.
     */
    private final Playwright playwright;
    /**
     * The currently active browser window (context).
     * <p>
     * Note: The setter is automatically generated by Lombok's {@code @Setter}.
     */
    @Setter
    private IBrowserWindow currentBrowserWindow;
    /**
     * Flag indicating whether {@link #close()} has been called on this browser instance.
     * Volatile so {@link io.github.jcd2052.browser.services.interfaces.IBrowserService#closeAll()}
     * running on another thread is seen by the thread that owns this browser.
     */
    @Getter(AccessLevel.NONE)
    private volatile boolean isClosed;
    /**
     * The configuration properties used to initialize browser contexts.
     */
    private final IBrowserProperties browserProperties;
    /**
     * Window wrappers keyed by their Playwright context, so every lookup of the same context returns
     * the same {@link IBrowserWindow} instance (with its current tab intact). Entries are removed
     * when their context closes.
     */
    @Getter(AccessLevel.NONE)
    private final Map<BrowserContext, IBrowserWindow> browserWindows = new LinkedHashMap<>();

    /**
     * Constructs a new {@code PlaywrightBrowser} instance.
     *
     * @param playwright        The Playwright driver process that owns the browser connection.
     * @param browser           The raw Playwright {@link Browser} object to be wrapped.
     * @param browserProperties The configuration properties defining viewport size, tracing, etc.
     */
    public PlaywrightBrowser(Playwright playwright, Browser browser, IBrowserProperties browserProperties) {
        this.playwright = playwright;
        this.browser = browser;
        this.browserProperties = browserProperties;
        isClosed = false;
    }

    /**
     * {@inheritDoc}
     * <p>
     * <b>Implementation Note:</b> This method creates a new Playwright {@code BrowserContext},
     * applying every emulation and session setting configured via {@link IBrowserProperties}
     * (viewport, locale, timezone, geolocation, permissions, device emulation, and an optional
     * preloaded storage state).
     */
    @Override
    public IBrowserWindow openNewWindow() {
        return createWindow(buildContextOptions());
    }

    /**
     * {@inheritDoc}
     * <p>
     * <b>Implementation Note:</b> Behaves exactly like {@link #openNewWindow()}, except the given
     * {@code storageStatePath} always takes precedence over
     * {@link IBrowserProperties#getStorageStatePath()} for this window.
     */
    @Override
    public IBrowserWindow openNewWindow(Path storageStatePath) {
        Browser.NewContextOptions options = buildContextOptions();
        if (storageStatePath != null) {
            options.setStorageStatePath(storageStatePath);
        }
        return createWindow(options);
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public Collection<IBrowserWindow> getBrowserWindows() {
        return browser.contexts()
                .stream()
                .map(this::getOrCreateWindow)
                .collect(Collectors.toList());
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public String getBrowserName() {
        return browser.browserType().name();
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public byte[] takeScreenshot() {
        return requireCurrentBrowserTab()
                .getPage()
                .screenshot(new Page.ScreenshotOptions().setFullPage(true));
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public void switchToWindow(IBrowserWindow window) {
        if (window.getCurrentBrowserTab() != null) {
            window.switchToTab(window.getCurrentBrowserTab());
        }
        setCurrentBrowserWindow(window);
    }

    /**
     * {@inheritDoc}
     * <p>
     * Closes the Playwright browser and then its driver process. The driver is always closed, even if
     * the browser fails to close or has already crashed, so no driver process is left running.
     * Calling this more than once has no effect.
     *
     * @throws RuntimeException the first failure raised while closing; a second failure is attached
     *                          to it as a suppressed exception.
     */
    @Override
    public void close() {
        if (isClosed) {
            return;
        }
        isClosed = true;

        RuntimeException failure = null;
        try {
            browser.close();
        } catch (RuntimeException e) {
            failure = e;
        }
        try {
            playwright.close();
        } catch (RuntimeException e) {
            if (failure == null) {
                failure = e;
            } else {
                failure.addSuppressed(e);
            }
        }
        browserWindows.clear();
        currentBrowserWindow = null;

        if (failure != null) {
            throw failure;
        }
    }

    /**
     * {@inheritDoc}
     * <p>
     * Also reports {@code true} when the underlying browser has disconnected on its own (for example
     * it crashed or was killed), so callers replace it instead of reusing a dead instance.
     */
    @Override
    public boolean isClosed() {
        return isClosed || !browser.isConnected();
    }


    /**
     * Creates and registers a new {@link IBrowserWindow} from the given, already-built context options.
     *
     * @param options the fully configured {@link Browser.NewContextOptions} to create the context with
     * @return the newly created, now-current {@link IBrowserWindow}.
     */
    private IBrowserWindow createWindow(Browser.NewContextOptions options) {
        IBrowserWindow browserWindow = getOrCreateWindow(browser.newContext(options));
        browserWindow.getBrowserContext().setDefaultTimeout(browserProperties.getTimeout());
        browserWindow.getBrowserContext().setDefaultNavigationTimeout(browserProperties.getPageLoadTimeout());
        setCurrentBrowserWindow(browserWindow);
        return browserWindow;
    }

    /**
     * Builds the Playwright {@link Browser.NewContextOptions} for a new window, translating every
     * configured {@link IBrowserProperties} emulation/session setting into the matching Playwright option.
     * <p>
     * Every setting beyond the viewport is optional: unset (null/blank) properties are simply omitted
     * from the options so Playwright falls back to its own defaults for that setting.
     * </p>
     *
     * @return the fully configured {@link Browser.NewContextOptions} for a new browser context.
     */
    private Browser.NewContextOptions buildContextOptions() {
        Browser.NewContextOptions options = new Browser.NewContextOptions()
                .setViewportSize(browserProperties.getWidth(), browserProperties.getHeight());

        if (isNotBlank(browserProperties.getLocale())) {
            options.setLocale(browserProperties.getLocale());
        }
        if (isNotBlank(browserProperties.getTimezoneId())) {
            options.setTimezoneId(browserProperties.getTimezoneId());
        }
        if (browserProperties.getGeolocationLatitude() != null && browserProperties.getGeolocationLongitude() != null) {
            options.setGeolocation(new Geolocation(
                    browserProperties.getGeolocationLatitude(),
                    browserProperties.getGeolocationLongitude()));
        }

        List<String> permissions = browserProperties.getPermissions();
        if (permissions != null && !permissions.isEmpty()) {
            options.setPermissions(permissions);
        }

        if (isNotBlank(browserProperties.getUserAgent())) {
            options.setUserAgent(browserProperties.getUserAgent());
        }
        if (browserProperties.getDeviceScaleFactor() != null) {
            options.setDeviceScaleFactor(browserProperties.getDeviceScaleFactor());
        }
        if (browserProperties.isMobile()) {
            options.setIsMobile(true);
        }
        if (browserProperties.isHasTouch()) {
            options.setHasTouch(true);
        }

        if (isNotBlank(browserProperties.getStorageStatePath())) {
            Path storageStatePath = Paths.get(browserProperties.getStorageStatePath());
            options.setStorageStatePath(storageStatePath);
        }

        return options;
    }

    /**
     * Returns the cached wrapper for the given context, creating and registering it on first sight.
     *
     * @param context the Playwright browser context to wrap
     * @return the {@link IBrowserWindow} wrapping {@code context}
     */
    private IBrowserWindow getOrCreateWindow(BrowserContext context) {
        IBrowserWindow window = browserWindows.get(context);
        if (window == null) {
            window = new BrowserWindow(context);
            browserWindows.put(context, window);
            context.onClose(this::forgetWindow);
        }
        return window;
    }

    /**
     * Drops a closed context's wrapper. If it was the current window, the most recently opened
     * remaining window becomes current (or {@code null} if none are left).
     *
     * @param context the context that was closed
     */
    private void forgetWindow(BrowserContext context) {
        IBrowserWindow closedWindow = browserWindows.remove(context);
        if (closedWindow != null && closedWindow == currentBrowserWindow) {
            currentBrowserWindow = browserWindows.values().stream().reduce((first, second) -> second).orElse(null);
        }
    }

    private static boolean isNotBlank(String value) {
        return value != null && !value.trim().isEmpty();
    }
}
